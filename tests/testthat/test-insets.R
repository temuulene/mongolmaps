test_that("inset maps share scales without changing analytical geometry", {
  skip_if_not_installed("patchwork")
  skip_if_not_installed("ggplot2")
  x <- mn_aimags()
  x$value <- seq_len(nrow(x))
  original <- sf::st_as_binary(sf::st_geometry(x))
  p <- mn_inset_ub(x, fill = value)
  expect_s3_class(p, "patchwork")
  expect_equal(sf::st_as_binary(sf::st_geometry(x)), original)
  expect_equal(nrow(attr(p, "mongolmaps_panels")$ulaanbaatar), 1)
  expect_s3_class(patchwork::patchworkGrob(p), "gtable")
  expect_equal(p$patches$plots[[1]]$scales$get_scales("fill")$limits, range(x$value))
  binned <- mn_inset_ub(x, fill = value, bins = 4)
  expect_s3_class(patchwork::patchworkGrob(binned), "gtable")
  expect_error(mn_inset_ub(x[x$pcode != "MN11", ], fill = value), "No Ulaanbaatar")
})

test_that("urban panels cover all units once and use separate geographic scales", {
  skip_if_not_installed("patchwork")
  skip_if_not_installed("ggplot2")
  x <- mn_ub_districts()
  x$rate <- seq_len(nrow(x))
  p <- mn_map_ub(x, fill = rate)
  parts <- attr(p, "mongolmaps_panels")
  expect_equal(sum(vapply(parts, nrow, integer(1))), nrow(x))
  expect_setequal(unlist(lapply(parts, function(z) z$pcode)), x$pcode)
  expect_equal(nrow(parts$baganuur), 1)
  expect_equal(nrow(parts$bagakhangai), 1)
  expect_s3_class(patchwork::patchworkGrob(p), "gtable")
  expect_error(mn_map_ub(mn_aimags()), "only Ulaanbaatar")
})

test_that("choropleth scales support comparisons, bins, differences and missing values", {
  skip_if_not_installed("ggplot2")
  x <- mn_aimags()
  x$value <- seq_len(nrow(x))
  p <- mn_map(x, fill = value, limits = c(0, 30), breaks = c(0, 10, 20, 30))
  expect_equal(p$scales$get_scales("fill")$limits, c(0, 30))
  p <- mn_map(x, fill = value, bins = c(-Inf, 5, 15, Inf))
  expect_s3_class(p$scales$get_scales("fill"), "ScaleDiscrete")
  expect_equal(length(levels(p$layers[[1]]$data$..fill_bin)), 3)
  expect_s3_class(ggplot2::ggplot_build(p), "ggplot_built")
  p <- mn_map(x, fill = value - 10, midpoint = 0)
  expect_s3_class(p$scales$get_scales("fill"), "ScaleContinuous")
  x$value[1] <- NA
  expect_match(mn_map(x, fill = value)$labels$caption, "Grey: No data")
  expect_match(mn_map(mn_settlements())$labels$caption, "Wikidata")
})

test_that("water erasing preserves input areas and computes a separate land area", {
  rect <- function(a, b) sf::st_polygon(list(matrix(c(a, 0, b, 0, b, 100, a, 100, a, 0), ncol = 2, byrow = TRUE)))
  x <- sf::st_sf(area_km2 = c(0.01, 0.01), geometry = sf::st_sfc(rect(0, 100), rect(100, 200), crs = 32648))
  water <- sf::st_sf(geometry = sf::st_sfc(rect(0, 25), crs = 32648))
  original <- sf::st_as_binary(sf::st_geometry(x))
  y <- mn_erase_water(x, water)
  expect_equal(y$area_km2, x$area_km2)
  expect_equal(sf::st_as_binary(sf::st_geometry(x)), original)
  # Equal-area projection can differ slightly from the synthetic UTM areas.
  expect_equal(y$land_area_km2[1] / y$land_area_km2[2], 0.75, tolerance = 1e-4)
  y <- mn_erase_water(x, x)
  expect_equal(nrow(y), nrow(x))
  expect_true(all(sf::st_is_empty(y)))
})

test_that("label points are recomputed for modified geometries", {
  x <- mn_aimags()[1, ]
  shifted <- sf::st_geometry(sf::st_transform(x, 32648)) + c(100000, 100000)
  sf::st_geometry(x) <- sf::st_transform(sf::st_set_crs(shifted, 32648), 4326)
  p <- mn_label_points(x)
  expect_true(lengths(sf::st_intersects(p, x)) > 0)
})
